-- Run once against a Supabase project. All money is integer Malaysian sen.
begin;

create table public.shop_admins (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);
alter table public.shop_admins enable row level security;
revoke all on public.shop_admins from anon, authenticated;

-- Membership can only be managed by trusted database/server credentials.
create function public.is_shop_admin()
returns boolean
language sql stable security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.shop_admins where user_id = (select auth.uid())
  );
$$;
revoke all on function public.is_shop_admin() from public, anon;
grant execute on function public.is_shop_admin() to authenticated;

create table public.products (
  id text primary key check (id ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  name text not null check (length(trim(name)) > 0),
  family text not null check (family in ('floral', 'fruity', 'woody', 'fresh', 'amber')),
  description text not null default '',
  price_sen integer check (price_sen > 0),
  size text,
  notes_top text[] not null default '{}',
  notes_heart text[] not null default '{}',
  notes_base text[] not null default '{}',
  image_path text,
  image_alt text not null default '',
  is_active boolean not null default true,
  is_purchasable boolean not null default false,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (not is_purchasable or (is_active and price_sen is not null and length(trim(size)) > 0 and size is not null))
);

create table public.inventory (
  product_id text primary key references public.products(id) on delete restrict,
  stock_on_hand integer not null default 0 check (stock_on_hand >= 0),
  stock_reserved integer not null default 0 check (stock_reserved >= 0),
  updated_at timestamptz not null default now(),
  check (stock_reserved <= stock_on_hand)
);

create table public.orders (
  id uuid primary key default gen_random_uuid(),
  order_number bigint generated always as identity unique,
  -- Generated by the backend: SHA-256 of a random, high-entropy guest token.
  -- Never use the sequential order number as authorization.
  guest_token_hash text not null unique check (guest_token_hash ~ '^[a-f0-9]{64}$'),
  checkout_request_id uuid not null unique,
  customer_name text not null check (length(trim(customer_name)) between 1 and 200),
  customer_email text not null check (length(trim(customer_email)) between 3 and 254),
  customer_phone text not null check (length(trim(customer_phone)) between 5 and 30),
  shipping_address_line1 text not null check (length(trim(shipping_address_line1)) > 0),
  shipping_address_line2 text,
  shipping_city text not null check (length(trim(shipping_city)) > 0),
  shipping_state text not null check (length(trim(shipping_state)) > 0),
  shipping_postcode text not null check (length(trim(shipping_postcode)) > 0),
  shipping_country text not null default 'MY' check (shipping_country = 'MY'),
  currency text not null default 'MYR' check (currency = 'MYR'),
  subtotal_sen bigint not null check (subtotal_sen >= 0),
  shipping_sen integer not null check (shipping_sen >= 0),
  total_sen bigint generated always as (subtotal_sen + shipping_sen) stored,
  payment_status text not null default 'awaiting_payment'
    check (payment_status in ('awaiting_payment', 'awaiting_verification', 'paid', 'proof_rejected', 'refunded')),
  fulfillment_status text not null default 'unfulfilled'
    check (fulfillment_status in ('unfulfilled', 'processing', 'shipped', 'delivered', 'cancelled')),
  customer_note text,
  payment_due_at timestamptz not null,
  reservation_expires_at timestamptz not null,
  paid_at timestamptz,
  courier text,
  tracking_number text,
  shipped_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (payment_status <> 'paid' or paid_at is not null),
  check (fulfillment_status not in ('processing', 'shipped', 'delivered') or payment_status in ('paid', 'refunded'))
);

create table public.order_items (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders(id) on delete restrict,
  product_id text not null references public.products(id) on delete restrict,
  product_name text not null check (length(trim(product_name)) > 0),
  product_size text not null check (length(trim(product_size)) > 0),
  unit_price_sen integer not null check (unit_price_sen > 0),
  quantity integer not null check (quantity between 1 and 999),
  line_total_sen bigint generated always as (unit_price_sen::bigint * quantity) stored,
  unique (order_id, product_id)
);

-- One record for every upload attempt; resubmissions get new records/paths.
create table public.payment_submissions (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders(id) on delete restrict,
  receipt_path text not null unique,
  content_type text not null check (content_type in ('image/jpeg', 'image/png', 'image/webp')),
  file_size_bytes integer not null check (file_size_bytes between 1 and 5242880),
  bank_reference text,
  status text not null default 'pending_review'
    check (status in ('pending_review', 'approved', 'rejected')),
  submitted_at timestamptz not null default now(),
  reviewed_at timestamptz,
  reviewed_by uuid references auth.users(id) on delete restrict,
  rejection_reason text,
  -- Store objects at <order UUID>/<submission UUID>.<extension>.
  check (receipt_path in (
    order_id::text || '/' || id::text || '.jpg',
    order_id::text || '/' || id::text || '.png',
    order_id::text || '/' || id::text || '.webp'
  )),
  check (
    (status = 'pending_review' and reviewed_at is null and reviewed_by is null and rejection_reason is null)
    or (status = 'approved' and reviewed_at is not null and reviewed_by is not null and rejection_reason is null)
    or (status = 'rejected' and reviewed_at is not null and reviewed_by is not null
      and rejection_reason is not null and length(trim(rejection_reason)) > 0)
  )
);
create unique index one_pending_receipt_per_order on public.payment_submissions(order_id)
  where status = 'pending_review';
create unique index one_approved_receipt_per_order on public.payment_submissions(order_id)
  where status = 'approved';

create table public.order_events (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders(id) on delete restrict,
  actor_id uuid references auth.users(id) on delete set null,
  event_type text not null check (length(trim(event_type)) > 0),
  details jsonb not null default '{}'::jsonb check (jsonb_typeof(details) = 'object'),
  created_at timestamptz not null default now()
);

create index orders_payment_queue on public.orders(payment_status, created_at);
create index orders_fulfillment_queue on public.orders(fulfillment_status, created_at);
create index orders_reservation_expiry on public.orders(reservation_expires_at)
  where payment_status in ('awaiting_payment', 'awaiting_verification', 'proof_rejected');
create index order_events_order_id on public.order_events(order_id, created_at);
create index payment_submissions_order_id on public.payment_submissions(order_id, submitted_at);
-- order_items already has an index beginning with order_id via its unique constraint.
create index order_items_product_id on public.order_items(product_id);

create function public.set_shop_updated_at()
returns trigger language plpgsql set search_path = '' as $$
begin
  new.updated_at = now();
  return new;
end;
$$;
revoke all on function public.set_shop_updated_at() from public, anon, authenticated;
create trigger products_updated_at before update on public.products
  for each row execute function public.set_shop_updated_at();
create trigger inventory_updated_at before update on public.inventory
  for each row execute function public.set_shop_updated_at();
create trigger orders_updated_at before update on public.orders
  for each row execute function public.set_shop_updated_at();

alter table public.products enable row level security;
alter table public.inventory enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;
alter table public.payment_submissions enable row level security;
alter table public.order_events enable row level security;

revoke all on public.products, public.inventory, public.orders, public.order_items,
  public.payment_submissions, public.order_events from anon, authenticated;
revoke all on sequence public.orders_order_number_seq from anon, authenticated;
grant select on public.products to anon, authenticated;
grant select on public.inventory, public.orders, public.order_items,
  public.payment_submissions, public.order_events to authenticated;
grant all on public.shop_admins, public.products, public.inventory, public.orders,
  public.order_items, public.payment_submissions, public.order_events to service_role;
grant usage, select on sequence public.orders_order_number_seq to service_role;

create policy catalogue_anon_read on public.products for select to anon using (is_active);
create policy catalogue_authenticated_read on public.products for select to authenticated
  using (is_active or (select public.is_shop_admin()));
create policy inventory_admin_read on public.inventory for select to authenticated
  using ((select public.is_shop_admin()));
create policy orders_admin_read on public.orders for select to authenticated
  using ((select public.is_shop_admin()));
create policy order_items_admin_read on public.order_items for select to authenticated
  using ((select public.is_shop_admin()));
create policy receipts_admin_read on public.payment_submissions for select to authenticated
  using ((select public.is_shop_admin()));
create policy order_events_admin_read on public.order_events for select to authenticated
  using ((select public.is_shop_admin()));

comment on table public.orders is
  'Guest access and all mutations require trusted backend functions. Never return guest_token_hash to clients.';
comment on table public.inventory is
  'Checkout must lock inventory rows and reserve stock atomically; this schema alone does not reserve stock.';
comment on table public.order_events is
  'Backend must append audit events in the same transaction as order/payment changes.';

commit;
